import { VageError } from "../core/errors.js";
import type { SiteRedirect } from "../core/site.js";
import { ruleData } from "../guidelines/pack.js";

// https://developers.cloudflare.com/pages/configuration/redirects/ (rule pack "cloudflare.redirects")
const { maxStaticRules } = ruleData<{ maxStaticRules: number }>("cloudflare.redirects");

/**
 * Cloudflare Pages `_redirects`: real 301s for configured redirects. The
 * meta-refresh pages stay as a fallback for hosts without redirect support.
 * Both "/old" and "/old/" are listed so either form redirects.
 */
export function cloudflareRedirects(redirects: SiteRedirect[]): string {
  const lines = redirects.flatMap((r) => {
    const sources = r.from === "/" ? ["/"] : [r.from, r.from.replace(/\/$/, "")];
    return sources.map((from) => `${from} ${r.to} 301`);
  });
  if (lines.length > maxStaticRules) throw new VageError(`_redirects would have ${lines.length} rules; Cloudflare Pages allows ${maxStaticRules}.`);
  return `# Generated by vagejs from redirects in vage.config.ts\n${lines.join("\n")}\n`;
}

/**
 * Netlify `_redirects`: the same rules, forced ("301!"). Netlify serves an existing file
 * before a redirect, and vagejs writes an HTML forwarding page at each old address.
 */
export function netlifyRedirects(redirects: SiteRedirect[]): string {
  const lines = redirects.flatMap((r) => (r.from === "/" ? ["/"] : [r.from, r.from.replace(/\/$/, "")]).map((from) => `${from} ${r.to} 301!`));
  return `# Generated by vagejs from redirects in vage.config.ts\n${lines.join("\n")}\n`;
}
