import { createHash } from "node:crypto";
import { parse } from "node-html-parser";
import type { SiteConfig } from "../core/config.js";
import { VageError } from "../core/errors.js";
import { ruleData } from "../guidelines/pack.js";

// https://developers.cloudflare.com/pages/configuration/headers/ (rule pack "cloudflare.headers", "csp.providers")
const { maxLineLength, maxRules } = ruleData<{ maxLineLength: number; maxRules: number }>("cloudflare.headers");
type Directive = "script-src" | "style-src" | "img-src" | "font-src" | "connect-src" | "frame-src" | "media-src";
const PROVIDERS = ruleData<Record<"google" | "clarity", Partial<Record<Directive, string[]>>>>("csp.providers");

const EXECUTABLE = /^(|module|text\/javascript|application\/javascript)$/i;

/**
 * Content Security Policy derived from the built HTML: sha256 hashes of every
 * inline script and <style>, the external origins layouts load, and the
 * documented domains of configured analytics. Scripts are locked down (that
 * is where XSS protection comes from); images, fonts and media may come from
 * any https origin so ordinary sites don't break.
 */
export function contentSecurityPolicy(pagesHtml: string[], site: SiteConfig): string {
  const sources: Record<Directive, Set<string>> = {
    "script-src": new Set(["'self'"]),
    "style-src": new Set(["'self'"]),
    "img-src": new Set(["'self'", "data:", "https:"]),
    "font-src": new Set(["'self'", "data:", "https:"]),
    "connect-src": new Set(["'self'"]),
    "frame-src": new Set(),
    "media-src": new Set(["'self'", "https:"]),
  };
  const hash = (text: string) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;
  const origin = (url: string | undefined) => {
    if (!url || !/^https?:\/\//i.test(url)) return undefined;
    const o = new URL(url).origin;
    return site.site && o === site.site ? undefined : o;
  };

  for (const html of pagesHtml) {
    const doc = parse(html);
    for (const s of doc.querySelectorAll("script")) {
      if (!EXECUTABLE.test(s.getAttribute("type") ?? "")) continue; // e.g. JSON-LD is data, not code
      const src = s.getAttribute("src");
      if (src) {
        const o = origin(src);
        if (o) sources["script-src"].add(o);
      } else if (s.rawText.trim()) sources["script-src"].add(hash(s.rawText));
    }
    for (const s of doc.querySelectorAll("style")) sources["style-src"].add(hash(s.rawText));
    for (const l of doc.querySelectorAll('link[rel="stylesheet"]')) {
      const o = origin(l.getAttribute("href"));
      if (o) sources["style-src"].add(o);
    }
    for (const f of doc.querySelectorAll("iframe[src]")) {
      const o = origin(f.getAttribute("src"));
      if (o) sources["frame-src"].add(o);
    }
  }

  const { ga4, gtm, plausible, clarity } = site.integrations;
  const add = (extra: Partial<Record<Directive, string[]>>) => {
    for (const [d, list] of Object.entries(extra) as [Directive, string[]][]) list.forEach((v) => sources[d].add(v));
  };
  if (ga4?.measurementId || gtm?.containerId) add(PROVIDERS.google);
  if (clarity) add(PROVIDERS.clarity);
  if (plausible) {
    // Plausible's snippet loads its script from, and reports to, the same origin.
    for (const m of plausible.snippet.matchAll(/src=["']([^"']+)["']/g)) {
      const o = origin(m[1]);
      if (o) add({ "script-src": [o], "connect-src": [o] });
    }
  }
  add(site.security.cspSources);

  const directives = [
    "default-src 'self'",
    ...(Object.entries(sources) as [Directive, Set<string>][]).filter(([, v]) => v.size).map(([d, v]) => `${d} ${[...v].join(" ")}`),
    "style-src-attr 'unsafe-inline'", // style="" attributes in content; CSS can't run script
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'self'",
    "upgrade-insecure-requests",
  ];
  return directives.join("; ");
}

/**
 * Markdown copies can name their HTML page as canonical with one rule each, while the
 * file stays within Cloudflare's rule limit (the first rule covers every path).
 */
export const copyCanonicalsFit = (copies: number) => copies + 1 <= maxRules;

/**
 * Cloudflare Pages / Netlify `_headers` for every path, plus a canonical Link header on
 * each Markdown copy (`copies`: its path and its page's URL) when they fit.
 */
export function headersFile(pagesHtml: string[], site: SiteConfig, copies: { path: string; canonical: string }[] = []): string {
  const lines = ["# Generated by vagejs (security in vage.config.ts)", "/*", "  X-Content-Type-Options: nosniff", "  Referrer-Policy: strict-origin-when-cross-origin", "  X-Frame-Options: SAMEORIGIN", "  Permissions-Policy: camera=(), microphone=(), geolocation=()"];
  if (site.security.csp !== "off") {
    const name = site.security.csp === "report-only" ? "Content-Security-Policy-Report-Only" : "Content-Security-Policy";
    lines.push(`  ${name}: ${contentSecurityPolicy(pagesHtml, site)}`);
  }
  const tooLong = lines.find((l) => l.length > maxLineLength);
  if (tooLong) {
    throw new VageError(
      `The generated Content-Security-Policy is ${tooLong.length} characters; _headers lines are limited to ${maxLineLength}. ` +
        "Reduce distinct inline scripts/styles (move them to files in public/), or set security.csp to \"off\".",
    );
  }
  if (copyCanonicalsFit(copies.length)) {
    for (const c of copies) lines.push(c.path, `  Link: <${c.canonical}>; rel="canonical"`);
  }
  return `${lines.join("\n")}\n`;
}
