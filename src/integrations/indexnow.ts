import { VageError } from "../core/errors.js";
import { ruleData } from "../guidelines/pack.js";
import { apiError, requestWithRetry, type HttpOptions } from "./http.js";

// https://www.indexnow.org/documentation (rule pack "indexnow.protocol")
const { maxUrls } = ruleData<{ maxUrls: number }>("indexnow.protocol");

export interface IndexNowResult {
  endpoint: string;
  submitted: number;
  /** 200 = accepted; 202 = received, key validation pending. */
  status: number;
}

/**
 * Notifies IndexNow-participating search engines that URLs changed. A hint,
 * not a guarantee of crawling or indexing. The key file must already be live.
 */
export async function submitIndexNow(options: { site: string; key: string; endpoint: string; urls: string[]; http?: HttpOptions }): Promise<IndexNowResult> {
  const { site, key, endpoint, http } = options;
  const host = new URL(site).host;
  const urls = [...new Set(options.urls)];
  if (!urls.length) throw new VageError("No URLs to submit.");
  const foreign = urls.filter((u) => new URL(u).host !== host);
  if (foreign.length) throw new VageError(`IndexNow only accepts URLs on ${host}: ${foreign.slice(0, 3).join(", ")}`);
  if (urls.length > maxUrls) throw new VageError(`IndexNow accepts at most ${maxUrls} URLs per request; got ${urls.length}.`);

  // Without a live key file the endpoint answers 403; check first for a clearer message.
  const keyLocation = `${new URL(site).origin}/${key}.txt`;
  const doFetch = http?.fetch ?? fetch;
  const live = await doFetch(keyLocation, { signal: AbortSignal.timeout(30_000) }).catch(() => undefined);
  if (!live?.ok || (await live.text()).trim() !== key) {
    throw new VageError(`The key file ${keyLocation} is not live yet. Deploy the site (it is generated by vage build), then submit.`);
  }

  const res = await requestWithRetry(
    "IndexNow",
    endpoint,
    { method: "POST", headers: { "content-type": "application/json; charset=utf-8" }, body: JSON.stringify({ host, key, keyLocation, urlList: urls }) },
    [],
    { ...http, attempts: 1 }, // the docs warn that 429 may mark submissions as spam; don't hammer
  );
  if (res.status !== 200 && res.status !== 202) {
    throw await apiError("IndexNow", res, [], {
      400: "The request was malformed.",
      403: "The key is not valid: the key file was not found or doesn't contain the key.",
      422: "The URLs don't belong to the host, or the key doesn't match.",
      429: "Too many requests; IndexNow may treat this as spam. Submit only changed URLs, less often.",
    });
  }
  return { endpoint, submitted: urls.length, status: res.status };
}
